/*
 * Модель доступа установлена по фактическому коду, а не по названию таблицы.
 *
 * `has_community_access` требует активную запись с не истёкшим `expires_at`, то есть доступ
 * ограничен сроком. При этом автоматического продления и повторного списания в проекте НЕТ
 * нигде: ни планировщика, ни rebill, ни хранения платёжного токена. Называть это подпиской
 * значило бы ввести в заблуждение и пользователя, и банк.
 *
 * Фактическая модель: разовая оплата, открывающая доступ на период.
 */
export const ACCESS_MODEL = 'one_time_period';

/*
 * Приём платежей выключен: функция `telegram` отвечает на `{"action":"invoice"}` кодом 403,
 * никакой оплаты в проекте не происходит. Цена и доступность оплаты — разные факты, поэтому
 * флаг отдельный: назначенная сумма не должна заставлять интерфейс утверждать, что доступ
 * можно купить прямо сейчас. Включать только вместе с реальным приёмом платежей.
 */
export const PAYMENTS_ENABLED = false;

export const PLAN = {
  id: 'community_access',
  name: 'Доступ к картам сообщества',
  /** Цена в рублях, назначена владельцем. null — снять сумму с публикации. */
  amount: 199,
  currency: 'RUB',
  /** Длительность периода доступа в днях. */
  periodDays: 30,
  /** Автопродления нет: по окончании периода доступ просто заканчивается. */
  autoRenew: false
};

/** Есть ли у нас право показывать конкретную сумму. */
export function priceIsPublished() {
  return Number.isFinite(PLAN.amount) && PLAN.amount > 0;
}

/** Строка стоимости для интерфейса. Без цены — честная формулировка, без выдуманных чисел. */
export function priceLabel() {
  if (!priceIsPublished()) return 'Стоимость уточняется';
  return `${PLAN.amount} ₽ единоразово за ${PLAN.periodDays} дней доступа`;
}

/** Как называется модель доступа в текстах. */
export function accessModelLabel() {
  return `разовая оплата за ${PLAN.periodDays} дней доступа, без автоматического продления`;
}
